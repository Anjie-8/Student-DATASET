import random
import csv

departments = ["Computer Science", "Cyber Security", "Software Engineering", "Information Technology"]
levels = [100, 200, 300, 400]

with open("students.csv", "w", newline="") as file:
    writer = csv.writer(file)
    writer.writerow(["Student ID", "Department", "Level", "Attendance %", "Average Exam Score"])

    for i in range(1, 51):
        writer.writerow([
            f"STU{i:03d}",
            random.choice(departments),
            random.choice(levels),
            random.randint(50, 100),
            random.randint(30, 100),
        ])

print("students.csv created")

